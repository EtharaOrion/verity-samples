def _scalar(text):
    text = text.strip()
    if text == "" or text == "null" or text == "~":
        return None
    if text in ("true", "True"):
        return True
    if text in ("false", "False"):
        return False
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "'\"":
        return text[1:-1]
    if re.fullmatch(r"-?\d+", text):
        return int(text)
    if re.fullmatch(r"-?\d*\.\d+([eE][-+]?\d+)?", text):
        return float(text)
    return text


def _strip_comments(lines):
    return [raw.rstrip("\n") for raw in lines if not raw.strip().startswith("#")]


def _indent(line):
    return len(line) - len(line.lstrip(" "))


def _split_key(text):
    """Split "key: value" on a colon followed by a space or end of line.

    A bare colon inside a scalar, as in HOLD:PILOT_REQUIRED, is not a key separator. Getting this wrong
    turns a list of sentences into a list of one-key mappings, which is exactly the class of silent
    mis-parse this reader has to not have.
    """
    if text.endswith(":"):
        return text[:-1], ""
    position = text.find(": ")
    if position == -1:
        return None, None
    return text[:position], text[position + 2 :]


def _parse_block(lines, index, indent):
    while index < len(lines) and lines[index].strip() == "":
        index += 1
    if index >= len(lines):
        return None, index
    if lines[index].lstrip().startswith("- "):
        return _parse_sequence(lines, index, indent)
    return _parse_mapping(lines, index, indent)


def _parse_folded(lines, index, indent):
    parts = []
    while index < len(lines):
        line = lines[index]
        if line.strip() == "":
            index += 1
            continue
        if _indent(line) <= indent:
            break
        parts.append(line.strip())
        index += 1
    return " ".join(parts), index


def _parse_mapping(lines, index, indent):
    result = {}
    while index < len(lines):
        line = lines[index]
        if line.strip() == "":
            index += 1
            continue
        current = _indent(line)
        if current < indent:
            break
        if current > indent:
            raise ValueError("unexpected indent at line %d: %r" % (index + 1, line))
        stripped = line.strip()
        if stripped.startswith("- "):
            break
        key, rest = _split_key(stripped)
        if key is None:
            raise ValueError("expected a mapping key at line %d: %r" % (index + 1, line))
        key, rest = key.strip(), rest.strip()
        index += 1
        if rest in (">-", ">"):
            value, index = _parse_folded(lines, index, current)
        elif rest == "":
            nested, index = _parse_block(lines, index, current + 2)
            value = nested
        else:
            value = _scalar(rest)
        result[key] = value
    return result, index


def _parse_sequence(lines, index, indent):
    items = []
    while index < len(lines):
        line = lines[index]
        if line.strip() == "":
            index += 1
            continue
        current = _indent(line)
        if current < indent or not line.lstrip().startswith("- "):
            break
        body = line.lstrip()[2:]
        index += 1
        key, rest = (None, None) if body.strip().startswith(("'", '"')) else _split_key(body.strip())
        if key is not None:
            entry = {}
            rest = rest.strip()
            if rest in (">-", ">"):
                value, index = _parse_folded(lines, index, current + 2)
            elif rest == "":
                value, index = _parse_block(lines, index, current + 4)
            else:
                value = _scalar(rest)
            entry[key.strip()] = value
            more, index = _parse_mapping(lines, index, current + 2)
            entry.update(more or {})
            items.append(entry)
        else:
            items.append(_scalar(body))
    return items, index


def read_yaml(path):
    with open(path, "r", encoding="utf-8") as handle:
        lines = _strip_comments(handle.readlines())
    value, _index = _parse_block(lines, 0, 0)
    return value or {}


