def excluded(rel):
    if any(part in IDENTITY_EXCLUDED_BASENAMES for part in rel.split("/")):
        return True
    if rel.endswith(".pyc"):
        return True
    for prefix in IDENTITY_EXCLUDED_PATHS:
        if rel == prefix or rel.startswith(prefix + "/"):
            return True
    return False


def normalize_canary_slots(text):
    """Replace the value of every designated slot with the fixed placeholder, and change nothing else."""

    def scrub(match):
        return CANARY_TOKEN_RE.sub(CANARY_PLACEHOLDER, match.group(0))

    return BLOCK_RE.sub(scrub, text)


def strip_binding_block(text):
    index = text.find(BINDING_MARKER)
    return text if index < 0 else text[:index]


def normalized_bytes(rel, raw):
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return raw
    if rel == "solution/provenance.yaml":
        text = strip_binding_block(text)
    return normalize_canary_slots(text).encode("utf-8")


def canonical_content_hash(root):
    """Path-independent hash over the identity domain, discovered rather than enumerated."""
    records = []
    for directory, subdirs, files in os.walk(root):
        subdirs[:] = sorted(d for d in subdirs if d not in IDENTITY_EXCLUDED_BASENAMES)
        for name in sorted(files):
            path = os.path.join(directory, name)
            rel = os.path.relpath(path, root).replace(os.sep, "/")
            if excluded(rel):
                continue
            with open(path, "rb") as handle:
                records.append((rel, normalized_bytes(rel, handle.read())))
    if not records:
        raise ValueError("no identity member resolved under %s" % root)
    digest = hashlib.sha256()
    for rel, payload in sorted(records):
        digest.update(rel.encode("utf-8"))
        digest.update(b"\0")
        digest.update(hashlib.sha256(payload).hexdigest().encode("ascii"))
        digest.update(b"\n")
    return digest.hexdigest()


def canary_tokens(content_hash, count=CANARY_COUNT):
    material = hashlib.pbkdf2_hmac(
        "sha256", content_hash.encode("ascii"), CANARY_SALT, CANARY_ITERATIONS, dklen=16 * count
    )
    return [CANARY_PREFIX + material[i * 16 : (i + 1) * 16].hex().upper() for i in range(count)]


def canary_block(tokens, prefix="# "):
    lines = [prefix + BLOCK_BEGIN]
    for index, token in enumerate(tokens):
        lines.append("%s%d %s" % (prefix, index, token))
    lines.append(prefix + BLOCK_END)
    return "\n".join(lines)


def placeholder_block(prefix="# "):
    return canary_block([CANARY_PLACEHOLDER] * CANARY_COUNT, prefix)


def plant(text, tokens):
    """Substitute the real tokens into the placeholder slots of every block, in order."""

    def fill(match):
        body = match.group(0)
        for token in tokens:
            body = body.replace(CANARY_PLACEHOLDER, token, 1)
        return body

    return BLOCK_RE.sub(fill, text)


def validate_block(text, expected):
    blocks = BLOCK_RE.findall(text)
    if not blocks:
        return False, "missing canary block"
    if len(blocks) > 1:
        return False, "duplicated canary block, found %d" % len(blocks)
    found = CANARY_TOKEN_RE.findall(blocks[0])
    if len(found) != len(expected):
        return False, "malformed block, %d slots against %d" % (len(found), len(expected))
    for index, (actual, want) in enumerate(zip(found, expected)):
        if actual != want:
            return False, "slot %d does not hold its derived token" % index
    return True, "one format-valid block, every slot holds its derived token"


def uuid5_from(namespace_uuid, name):
    """RFC 4122 version 5 UUID, computed without importing uuid so the derivation is visible."""
    hex_ns = namespace_uuid.replace("-", "")
    digest = hashlib.sha1(bytes.fromhex(hex_ns) + name.encode("utf-8")).digest()
    b = bytearray(digest[:16])
    b[6] = (b[6] & 0x0F) | 0x50
    b[8] = (b[8] & 0x3F) | 0x80
    h = b.hex()
    return "%s-%s-%s-%s-%s" % (h[0:8], h[8:12], h[12:16], h[16:20], h[20:32])


