CANARY_DOMAIN_VERSION = "v2"
CANARY_SALT = b"verity/forge/canary/v2"
CANARY_ITERATIONS = 4096
CANARY_COUNT = 4
CANARY_PREFIX = "VERITY-CANARY-"
CANARY_BODY_LEN = 32
CANARY_TOKEN_RE = re.compile(CANARY_PREFIX + "[0-9A-F]{%d}" % CANARY_BODY_LEN)
CANARY_PLACEHOLDER = CANARY_PREFIX + "PLACEHOLDER" + "0" * (CANARY_BODY_LEN - len("PLACEHOLDER"))
# Assembled rather than written whole, and the reason is not style. A contiguous literal here would sit
# inside the identity domain and BLOCK_RE would match the span between the two assignments as a block with
# no slots in it, so this file would report a malformed block while carrying none. Splitting the literals
# leaves the planted block as the only match in this file.
BLOCK_BEGIN = CANARY_PREFIX + "BLOCK-BEGIN"
BLOCK_END = CANARY_PREFIX + "BLOCK-END"
BLOCK_RE = re.compile(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END), re.DOTALL)
BINDING_MARKER = "# BINDING BLOCK BELOW. EXCLUDED FROM canonical_content_hash."

IDENTITY_EXCLUDED_PATHS = ("trajectories", "solution/provenance.sig")
IDENTITY_EXCLUDED_BASENAMES = ("__pycache__", ".DS_Store")

