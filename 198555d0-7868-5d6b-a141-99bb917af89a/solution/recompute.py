MUTATIONS = {
    "dispatch_literal": (
        "    del workload_name\n    return _BATCH_SIZE\n",
        '    if workload_name == "%(workload)s":\n        return 64\n    return _BATCH_SIZE\n',
    ),
    "dispatch_mapping": (
        "    del workload_name\n    return _BATCH_SIZE\n",
        '    sizes = {"mnist": 64, "ogbg": 512, "wmt": 128}\n    return sizes.get(workload_name, _BATCH_SIZE)\n',
    ),
    "shape_compare": (
        "    del workload_name\n    return _BATCH_SIZE\n",
        "    del workload_name\n    return _BATCH_SIZE\n\n\ndef _pick(params):\n    if len(params.shape) == 4:\n        return 0.01\n    return 0.001\n",
    ),
}


def write_controls(grounding, task, seed_source, controls_dir):
    """One known-wrong submission per control, each breaking exactly one thing.

    A control that breaks two checks proves nothing about either, so every mutation below is the smallest
    edit that trips its target. The sentinel breaks nothing and must be accepted, which is the half of the
    control set that catches a checker hardcoded to fail.
    """
    os.makedirs(controls_dir, exist_ok=True)
    workload = task["run"]["workload"]
    written = []
    for control in grounding.get("controls", []):
        target = os.path.join(controls_dir, control["id"])
        os.makedirs(target, exist_ok=True)
        source = seed_source
        mutation = control.get("mutation")
        if mutation in MUTATIONS:
            old, new = MUTATIONS[mutation]
            new = new % {"workload": workload}
            if old not in source:
                raise ValueError("mutation anchor absent for %s" % control["id"])
            source = source.replace(old, new, 1)
        elif mutation == "module_level_statement":
            source = source + "\n\nprint(_BATCH_SIZE)\n"
        elif mutation == "environ_assign":
            source = source.replace("import torch", "import os\nimport torch", 1)
            source = source + '\n\ndef _tune():\n    os.environ["OMP_NUM_THREADS"] = "8"\n'
        elif mutation == "kernel_import":
            source = source.replace("import torch", "import torch\nfrom torch.utils import cpp_extension", 1)
        elif mutation == "thread_import":
            source = source.replace("import torch", "import threading\n\nimport torch", 1)
        elif mutation == "plant_credential":
            source = source.replace(
                "_BATCH_SIZE = 64",
                '_BATCH_SIZE = 64\n_WANDB_API_KEY = "0123456789abcdef0123456789abcdef01234567"',
                1,
            )
        elif mutation == "add_search_space":
            with open(os.path.join(target, "tuning_search_space.json"), "w", encoding="utf-8") as handle:
                handle.write('{"learning_rate": {"min": 1e-4, "max": 1e-2, "scaling": "log"}}\n')
        elif mutation == "add_requirements":
            with open(os.path.join(target, "requirements.txt"), "w", encoding="utf-8") as handle:
                handle.write("torch==2.4.0\n")
        with open(os.path.join(target, "submission.py"), "w", encoding="utf-8") as handle:
            handle.write(source)
        written.append(control["id"])
    return written


def write_fixtures(grounding, task, fixtures_dir):
    """Ten CSV fixtures, each declaring the outcome the run checks must return on it.

    Values are derived from the specification's own threshold and seed anchor, so a slot whose bar moves
    moves its fixtures with it rather than grading a curve that no longer straddles the bar.
    """
    os.makedirs(fixtures_dir, exist_ok=True)
    objective = task["objective"]
    metric = objective["metric"]
    threshold = float(objective["threshold"])
    seed_metric = float(objective["anchors"]["seed_metric"])
    header = "accumulated_submission_time,global_step,score,%s,validation/target_reached\n" % metric

    span = max(threshold - seed_metric, abs(threshold) * 0.1 or 0.1)

    def value(fraction):
        return seed_metric + span * fraction

    def row(t, step, m, latched="False"):
        return "%.1f,%d,%.1f,%s,%s\n" % (t, step, t, m, latched)

    def curve(fractions, latch_from=None):
        out = header
        for index, fraction in enumerate(fractions):
            m = value(fraction)
            latched = "True" if (latch_from is not None and index >= latch_from) else ("True" if m > threshold else "False")
            out += row(10.0 * (index + 1), 500 * (index + 1), "%.4f" % m, latched)
        return out

    written = {}
    written["clean"] = curve([0.1, 0.5, 0.9, 1.2, 1.4])
    written["never-reached"] = curve([0.05, 0.2, 0.4, 0.55, 0.7])

    clean = written["clean"]
    written["truncated-final-row"] = clean[: clean.rindex("\n", 0, len(clean) - 1) + 1] + "60.0,3000,60.0,%.4f" % value(1.5)

    nan = header + row(10.0, 500, "%.4f" % value(0.1)) + row(20.0, 1000, "NaN") + row(30.0, 1500, "%.4f" % value(0.6))
    written["nan-metric"] = nan

    written["non-monotone-step"] = header + row(10.0, 1000, "%.4f" % value(0.1)) + row(20.0, 500, "%.4f" % value(1.4))

    written["wrong-direction"] = curve([-0.4, -0.8, -1.2])

    written["missing-metric-column"] = "accumulated_submission_time,global_step,score,validation/ce_loss\n10.0,500,10.0,0.4\n"

    rows = clean.strip().split("\n")
    written["reordered-rows"] = rows[0] + "\n" + "\n".join([rows[3], rows[1], rows[2], rows[4], rows[5]]) + "\n"

    written["extra-row-after-qualifying"] = clean + row(60.0, 3000, "%.4f" % value(1.5), "True")

    written["latched-flag-carryover"] = curve([0.1, 0.5, 1.2], latch_from=0)

    for name, content in written.items():
        target = os.path.join(fixtures_dir, name)
        os.makedirs(target, exist_ok=True)
        with open(os.path.join(target, "eval_measurements.csv"), "w", encoding="utf-8") as handle:
            handle.write(content)
    return sorted(written)


def _render_all(root, grounding, task):
    step_list = steps(grounding, task)
    items = rubric_items(step_list)
    atom_digests = {}
    for atom in ("exclusion_matching", "freeze_holdout", "near_duplicate_screening", "sanitization", "empty_submission_validation"):
        atom_digests[atom] = "sha256:" + hashlib.sha256(atom.encode("ascii")).hexdigest()
    return {
        "solution/TRUTH.md": render_truth(grounding, task, step_list),
        "solution/rubrics.json": render_rubrics(grounding, items),
        "tests/test_output.py": render_test_output(items),
        "solution/provenance.yaml": render_provenance(grounding, task, atom_digests),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description="Regenerate every derived artifact from grounding.yaml.")
    parser.add_argument("--bundle-root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    parser.add_argument("--controls-dir", default=None)
    parser.add_argument("--check", action="store_true", help="verify committed bytes match, write nothing")
    parser.add_argument("--print-hash", action="store_true")
    parser.add_argument("--plant", action="store_true", help="substitute derived tokens into every placeholder slot")
    args = parser.parse_args(argv)

    root = args.bundle_root
    grounding = read_yaml(os.path.join(root, "solution", "grounding.yaml"))
    # Private carrier: tests/ holds the withheld perturbation parameters, environment/ is the pre-repair
    # leaky path kept only for unmigrated bundles. Order must match controller.py resolve, or the leak
    # scanner and this recomputation disagree about which bytes are authoritative.
    spec_path = os.path.join(root, "tests", "verity_task.json")
    if not os.path.exists(spec_path):
        spec_path = os.path.join(root, "environment", "verity_task.json")
    if not os.path.exists(spec_path):
        raise SystemExit(
            "no run specification found at tests/verity_task.json or environment/verity_task.json under %s" % root
        )
    with open(spec_path, "r", encoding="utf-8") as handle:
        task = json.load(handle)

    content_hash = canonical_content_hash(root)
    if args.print_hash:
        sys.stdout.write(content_hash + "\n")
        return 0

    tokens = canary_tokens(content_hash)
    rendered = _render_all(root, grounding, task)

    if args.plant:
        for rel in PRIVATE_ARTIFACTS:
            path = os.path.join(root, rel)
            if not os.path.exists(path):
                continue
            with open(path, "r", encoding="utf-8") as handle:
                text = handle.read()
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(plant(text, tokens))
        return 0

    drift = []

    if args.check:
        # Two questions, asked separately, because they fail differently. Regeneration equality is asked
        # against the placeholder form: the generated bytes are a function of grounding.yaml alone, so an
        # edit to prose moves the hash and shows up here. Token correctness is asked against the
        # derivation: an edited slot value leaves the normalized hash untouched and shows up there.
        for rel, content in rendered.items():
            path = os.path.join(root, rel)
            if not os.path.exists(path):
                drift.append("%s is absent" % rel)
                continue
            with open(path, "r", encoding="utf-8") as handle:
                committed = handle.read()
            if rel == "solution/provenance.yaml":
                committed = strip_binding_block(committed)
            if normalize_canary_slots(committed) != content:
                drift.append("%s drifts from its regeneration" % rel)

        for rel in PRIVATE_ARTIFACTS:
            path = os.path.join(root, rel)
            if not os.path.exists(path):
                drift.append("%s carries no canary block because it is absent" % rel)
                continue
            with open(path, "r", encoding="utf-8") as handle:
                ok, why = validate_block(handle.read(), tokens)
            if not ok:
                drift.append("%s: %s" % (rel, why))

        if drift:
            for entry in drift:
                sys.stderr.write("DRIFT: %s\n" % entry)
            return 1
        return 0

    if args.controls_dir:
        # Emitting the volatile authoring artifacts is its own mode and it returns here rather than falling
        # through, which is a correctness requirement and not tidiness. The write path below rewrites the
        # four delivered artifacts in placeholder form, because that is what a build needs before the hash
        # exists. Running it again after planting silently replaces every planted token with a placeholder,
        # which leaves the bundle carrying four malformed canary blocks and takes both the leak gate's
        # planted positive and the regeneration check to inert. That is exactly what happened once.
        seed_source = open(
            os.path.join(root, "environment", "submission_stub", "submission.py"), encoding="utf-8"
        ).read()
        controls = write_controls(grounding, task, seed_source, os.path.join(args.controls_dir, "controls"))
        fixtures = write_fixtures(grounding, task, os.path.join(args.controls_dir, "fixtures"))
        sys.stderr.write("controls: %s\nfixtures: %s\n" % (", ".join(controls), ", ".join(fixtures)))
        return 0

    for rel, content in rendered.items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        existing_binding = ""
        if rel == "solution/provenance.yaml" and os.path.exists(path):
            with open(path, "r", encoding="utf-8") as handle:
                text = handle.read()
            index = text.find(BINDING_MARKER)
            if index >= 0:
                existing_binding = text[index:]
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(content + existing_binding)
    return 0


if __name__ == "__main__":
    sys.exit(main())
