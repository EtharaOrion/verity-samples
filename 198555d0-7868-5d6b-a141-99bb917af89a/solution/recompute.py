#!/usr/bin/env python3
"""Private recomputation script. PRIVATE CARRIER.

Every generated artifact in this bundle descends from solution/grounding.yaml through this one pass, so the
executable oracle, the human-readable truth, the rubric, the compiled tests, the controls, and the fixtures
cannot disagree with each other.

Dependency-free on purpose. It runs inside the verifier image and inside a bare authoring checkout without
the bundle pinning a parser it would then have to trust, so it carries a reader for the restricted YAML
subset grounding.yaml is written in rather than importing one.

Identity is canary normalization domain v2, and the three-phase order matters. The canonical content hash
covers every runtime-relevant byte with each designated canary slot holding a fixed placeholder. The token
set is derived from that hash. The tokens are then planted into the slots, which the hash cannot see the
values of. The item 10i binding block is applied last and sits outside the hash entirely. So hashing
precedes planting, planting precedes binding, and no region of the identity domain is both mutable and
valid.

That ordering is why --check separates two questions that look like one. Regeneration equality is asked
against the placeholder form, because the generated bytes are a function of grounding.yaml alone. Token
correctness is asked separately against the derivation. An artifact whose slot value was altered therefore
fails derivation while the normalized hash is unchanged, and an artifact whose prose was altered moves the
hash. Two different defects, two different reports.

Generates:
  solution/TRUTH.md            the human-readable golden-trajectory projection
  solution/rubrics.json        the reference-based rubric
  tests/test_output.py         the deterministic tests compiled from that rubric
  solution/provenance.yaml     the per-unit provenance carrier, canonical payload only

Usage:
  python3 solution/recompute.py --bundle-root . [--controls-dir DIR] [--check] [--print-hash] [--plant]
"""

