def _yaml_scalar(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    text = str(value)
    if text == "" or any(ch in text for ch in ":#{}[],&*?|-<>=!%@`\"'\n") or text != text.strip():
        return json.dumps(text)
    return text


def write_yaml(node, indent=0):
    pad = "  " * indent
    out = []
    if isinstance(node, dict):
        for key in sorted(node):
            value = node[key]
            if isinstance(value, dict) and value:
                out.append("%s%s:" % (pad, key))
                out.append(write_yaml(value, indent + 1))
            elif isinstance(value, list) and value:
                out.append("%s%s:" % (pad, key))
                for item in value:
                    if isinstance(item, dict):
                        body = write_yaml(item, indent + 2).split("\n")
                        out.append("%s  - %s" % (pad, body[0].strip()))
                        out.extend(body[1:])
                    else:
                        out.append("%s  - %s" % (pad, _yaml_scalar(item)))
            elif isinstance(value, list):
                out.append("%s%s: []" % (pad, key))
            elif isinstance(value, dict):
                out.append("%s%s: {}" % (pad, key))
            else:
                out.append("%s%s: %s" % (pad, key, _yaml_scalar(value)))
    return "\n".join(out)


