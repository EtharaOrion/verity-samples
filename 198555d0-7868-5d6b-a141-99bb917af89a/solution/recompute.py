def render_test_output(items):
    """Compiled deterministic tests.

    Carries only the implied relation. No criterion prose and no reference text appears here, because
    test_output.py is reachable from the verifier tree in a way rubrics.json is not.
    """
    lines = ['"""%s"""' % BANNER, "", placeholder_block("# "), "", "import json", "import os", ""]
    lines.append('DETAIL = os.environ.get("VERITY_DETAIL", "/logs/verifier/verity_detail.json")')
    lines += ["", "", "def _results():", '    with open(DETAIL, "r", encoding="utf-8") as handle:',
              "        detail = json.load(handle)", "    table = {}",
              '    for entry in detail["checks"]:',
              '        table[entry["id"]] = table.get(entry["id"], True) and entry["passed"]',
              "    return table", "", ""]
    for item in items:
        checker = item["id"].split("-", 1)[1]
        lines.append("def test_%s():" % item["id"].lower().replace("-", "_"))
        lines.append("    assert _results().get(%r) is True" % checker)
        lines.append("")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


