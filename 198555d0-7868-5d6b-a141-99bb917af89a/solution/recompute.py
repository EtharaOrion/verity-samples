def rubric_items(step_list):
    """One atomic, independently gradable obligation per graded outcome.

    Every judgment reduces deterministically over named evidence, so every item is mode compiled and none
    is judged. compilation_floor for this project is 1.00, so a judged item would be a contract violation
    rather than an authoring choice.
    """
    checkers = [step["checker"] for step in step_list]
    weight = round(1.0 / len(checkers), 6)
    items = []
    for position, checker in enumerate(checkers):
        items.append(
            {
                "id": "R%02d-%s" % (position + 1, checker),
                "dimension": DIMENSION_FOR.get(checker, "rule"),
                "weight": weight,
                "evaluation_target": TARGET_FOR[checker],
                "criterion": step_list[position]["action"],
                "judgment": "the verifier result for %s is passed" % checker,
                "evidence": [TARGET_FOR[checker]],
                "mode": "compiled",
                "outcome_class": OUTCOME_FOR[checker],
            }
        )
    residual = round(1.0 - weight * len(items), 6)
    if residual:
        items[-1]["weight"] = round(items[-1]["weight"] + residual, 6)
    return items


